function hashString(str: string): number {
  let hash = 0;
  if (!str || str.length === 0) return 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0;
  }
  return Math.abs(hash);
}

export type ArtworkType = 'song' | 'album' | 'playlist' | 'artist' | 'profile';

/**
 * Returns a guaranteed valid, vibrant, aesthetic artwork URL.
 * Upgrades JioSaavn 50x50 and 150x150 to high-res 500x500 and enforces HTTPS.
 */
export function getAestheticArtwork(
  rawUrl?: string | null,
  type: ArtworkType = 'song',
  seedText: string = ''
): string {
  const seed = (seedText || '').toLowerCase();
  const hash = hashString(seed || type);

  // Detect broken, missing, black letterboxed YouTube, or default placeholders
  const isBadThumb =
    !rawUrl ||
    typeof rawUrl !== 'string' ||
    rawUrl.trim().length <= 10 ||
    rawUrl.includes('default_album') ||
    rawUrl.includes('artist-default') ||
    rawUrl.includes('default-film') ||
    rawUrl.includes('picsum.photos') ||
    rawUrl.includes('default-album') ||
    rawUrl.includes('hqdefault.jpg') ||
    rawUrl.includes('mqdefault.jpg') ||
    rawUrl.includes('default.jpg');

  // If this is a special show category (Horror, Standup, Podcasts, Audio Stories), prioritize curated AI posters
  const isSpecialCategory = /(horror|bhoot|haveli|khoon|chudail|paranormal|standup|comedy|joke|zakir|bassi|upmanyu|podcast|ranveer|trs|story|kahani|premchand|panchatantra)/i.test(seed);

  // If valid JioSaavn / high-res clean cover and not a special category forced to AI:
  if (!isBadThumb && rawUrl && (rawUrl.startsWith('http://') || rawUrl.startsWith('https://')) && (!isSpecialCategory || rawUrl.includes('saavncdn.com'))) {
    const secureUrl = rawUrl.replace(/^http:\/\//i, 'https://');
    return secureUrl.replace('150x150', '500x500').replace('50x50', '500x500');
  }

  if (type === 'profile') {
    return AI_PROFILE_AVATARS[hash % AI_PROFILE_AVATARS.length];
  }

  if (/(horror|bhoot|haveli|khoon|chudail|paranormal|shaitani|aatma|ghost|daravani)/i.test(seed)) {
    return AI_HORROR_ARTWORKS[hash % AI_HORROR_ARTWORKS.length];
  }

  if (/(standup|comedy|joke|zakir|bassi|upmanyu|munawar|harsh|haso|funny|hasya)/i.test(seed)) {
    return AI_STANDUP_ARTWORKS[hash % AI_STANDUP_ARTWORKS.length];
  }

  if (/(podcast|ranveer|trs|beerbiceps|interview|talk|crime|shamani|dostcast)/i.test(seed)) {
    return AI_PODCAST_ARTWORKS[hash % AI_PODCAST_ARTWORKS.length];
  }

  if (/(story|kahani|premchand|panchatantra|akbar|birbal|vikram|betal|katha)/i.test(seed)) {
    return AI_STORIES_ARTWORKS[hash % AI_STORIES_ARTWORKS.length];
  }

  if (/(ram|krishna|shiv|bhajan|aarti|chalisa|hanuman|devotional|gurbani|sufi|qawwali|shri|bhakti)/i.test(seed)) {
    return AI_DEVOTIONAL_ARTWORKS[hash % AI_DEVOTIONAL_ARTWORKS.length];
  }

  if (/(party|club|dj|dance|edm|disco|dhamaka|remix)/i.test(seed)) {
    return AI_PARTY_ARTWORKS[hash % AI_PARTY_ARTWORKS.length];
  }

  if (/(punjabi|sidhu|ap|dhillon|karan|aujla|diljit|dosanjh|bhangra|moose|haryanvi)/i.test(seed)) {
    return AI_PUNJABI_ARTWORKS[hash % AI_PUNJABI_ARTWORKS.length];
  }

  if (/(lofi|chill|relax|study|sleep|rain|slowed|ambient)/i.test(seed)) {
    return AI_LOFI_ARTWORKS[hash % AI_LOFI_ARTWORKS.length];
  }

  if (type === 'playlist') {
    return AI_PLAYLIST_ARTWORKS[hash % AI_PLAYLIST_ARTWORKS.length];
  }

  return AI_ALBUM_ARTWORKS[hash % AI_ALBUM_ARTWORKS.length];
}
